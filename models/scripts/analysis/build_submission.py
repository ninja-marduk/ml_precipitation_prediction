"""Assemble the GMD submission package, and quarantine everything else.

The paper directory had grown to 99 MB across 95 entries: three superseded
manuscript variants for three different journals, twenty-two .bak snapshots,
two previous submission archives, the LaTeX build products of all of them, and
four files whose names are a shell command that a broken quoting attempt wrote
to disk.

Nothing here is deleted except build products and those four. `.docs` is
excluded by .gitignore, so a delete in this tree is unrecoverable, and referee
reports, cover letters and previous submissions are records worth keeping even
when they are not part of this package. They move to `_archive/` instead, which
is a decision the author can reverse and a reader cannot mistake for the
submission.

What the package contains is derived from what the manuscript actually reads:
the two sources, the bibliography, and the figures resolved from their
`\\includegraphics` calls. A figure that is on disk but not included does not
travel, and a figure that is included but missing is an error rather than a
silent omission.

Usage:
  python models/scripts/analysis/build_submission.py --dry-run
  python models/scripts/analysis/build_submission.py
"""
from __future__ import annotations

import argparse
import re
import shutil
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
PAPER = ROOT / ".docs" / "papers" / "5"
OUT = PAPER / "submission"
ARCHIVE = PAPER / "_archive"

# Sources the package is built from. Everything else is derived from these.
SOURCES = ("paper_gmd.tex", "supplement.tex")
EXTRA = ("refs.bib", "paper_gmd.pdf", "supplement.pdf")

# Build products: regenerated by one pdflatex run, so deleting them loses nothing.
BUILD_SUFFIXES = {".aux", ".log", ".out", ".blg", ".fls", ".fdb_latexmk",
                  ".synctex.gz", ".toc", ".lof", ".lot", ".spl", ".abs"}
# .bbl is a build product too, but Copernicus asks for it, so the two current
# ones are kept and only the superseded manuscripts' copies are swept.
KEEP_BBL = {"paper_gmd.bbl", "supplement.bbl"}

# Class and style files the current documents load. Copernicus hosts these, but
# they travel so the package compiles anywhere.
CLASS_FILES = ("copernicus.cls", "copernicus.bst", "copernicus.cfg")

# Files whose names are a fragment of a shell command. A quoting failure wrote
# the output of four `cp` invocations to paths built from the mangled argument.
def is_mangled(name: str) -> bool:
    return "&&" in name or "d:github.com" in name


def figures_used(texts) -> set[str]:
    used = set()
    for tex in texts:
        for m in re.finditer(r"\\includegraphics(?:\[[^\]]*\])?\{([^}]+)\}", tex):
            used.add(m.group(1))
    return used


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()
    def emit(*a):
        # Some filenames in this tree contain characters the Windows console
        # codepage cannot encode, which is part of why they are being removed.
        line = " ".join(str(x) for x in a)
        prefix = "  [dry] " if args.dry_run else ""
        print(prefix + line.encode("ascii", "replace").decode("ascii"))

    say = emit

    if not PAPER.exists():
        print(f"no paper directory at {PAPER}")
        return 1

    texts = []
    for s in SOURCES:
        p = PAPER / s
        if not p.exists():
            print(f"FATAL: {s} is missing; nothing to build")
            return 1
        texts.append(p.read_text(encoding="utf-8"))

    wanted = figures_used(texts)
    missing = [f for f in sorted(wanted) if not (PAPER / "figures" / f).exists()]
    if missing:
        print(f"FATAL: {len(missing)} included figure(s) not on disk: {missing}")
        return 1
    raster = sorted(f for f in wanted if not f.endswith(".pdf"))
    if raster:
        print(f"NOTE: {len(raster)} included figure(s) are not vector: {raster}")

    # ---- 1. the package ----------------------------------------------------
    print("=" * 72)
    print("SUBMISSION PACKAGE")
    print("=" * 72)
    if not args.dry_run:
        if OUT.exists():
            shutil.rmtree(OUT)
        (OUT / "figures").mkdir(parents=True)
    total = 0
    for name in list(SOURCES) + list(EXTRA) + list(CLASS_FILES) + sorted(KEEP_BBL):
        src = PAPER / name
        if not src.exists():
            print(f"  missing (skipped): {name}")
            continue
        total += src.stat().st_size
        say(f"  {name}  ({src.stat().st_size/1024:.0f} KB)")
        if not args.dry_run:
            shutil.copy2(src, OUT / name)
    for f in sorted(wanted):
        src = PAPER / "figures" / f
        total += src.stat().st_size
        say(f"  figures/{f}  ({src.stat().st_size/1024:.0f} KB)")
        if not args.dry_run:
            shutil.copy2(src, OUT / "figures" / f)
    # The cover letter is uploaded on its own rather than inside the archive,
    # but it belongs to this submission and should not have to be hunted for
    # among the letters written for the three journals that came before.
    letter = PAPER / "letter" / "cover_letter_GMD.txt"
    if letter.exists():
        total += letter.stat().st_size
        say(f"  cover_letter_GMD.txt  ({letter.stat().st_size/1024:.0f} KB)")
        if not args.dry_run:
            shutil.copy2(letter, OUT / "cover_letter_GMD.txt")
    print(f"  ---- {total/1024/1024:.2f} MB in "
          f"{len(wanted) + len(SOURCES) + len(EXTRA) + len(CLASS_FILES) + 2} files")

    # ---- 2. delete build products and the mangled names --------------------
    print()
    print("=" * 72)
    print("DELETED  (regenerated by one pdflatex run, or not a real file)")
    print("=" * 72)
    freed = n_del = 0
    deleted = set()          # so the dry run reports the real sequence
    for p in sorted(PAPER.iterdir()):
        if p.is_dir() or p.name in KEEP_BBL:
            continue
        junk = (p.suffix in BUILD_SUFFIXES
                or ".bak" in p.name
                or p.suffix == ".bbl"
                or is_mangled(p.name))
        if not junk:
            continue
        freed += p.stat().st_size
        n_del += 1
        deleted.add(p.name)
        say(f"  {p.name[:70]}")
        if not args.dry_run:
            p.unlink()
    print(f"  ---- {n_del} files, {freed/1024/1024:.2f} MB")

    # ---- 3. quarantine the records -----------------------------------------
    print()
    print("=" * 72)
    print("MOVED TO _archive/  (kept, not part of this submission)")
    print("=" * 72)
    # The Spanish reading translation is not a submission artefact and never
    # will be, GMD publishing in English, but it is not a record either: it is
    # regenerated from the manuscript whenever the manuscript changes, and
    # assemble_translation.py writes it here. Moving it to _archive/ on every
    # build left the verifier looking for a file that was no longer where it
    # had put it.
    keep = (set(SOURCES) | set(EXTRA) | set(CLASS_FILES) | KEEP_BBL
            | {"paper_es.tex", "paper_es.pdf"})
    keep_dirs = {"figures", "submission", "_archive", "data"}
    moved = n_mv = 0
    if not args.dry_run:
        ARCHIVE.mkdir(exist_ok=True)
    for p in sorted(PAPER.iterdir()):
        if p.name in keep or p.name in keep_dirs or p.name in deleted:
            continue
        size = sum(f.stat().st_size for f in p.rglob("*") if f.is_file()) \
            if p.is_dir() else p.stat().st_size
        moved += size
        n_mv += 1
        say(f"  {p.name}{'/' if p.is_dir() else ''}  ({size/1024/1024:.1f} MB)")
        if not args.dry_run:
            dest = ARCHIVE / p.name
            if dest.exists():
                shutil.rmtree(dest) if dest.is_dir() else dest.unlink()
            shutil.move(str(p), str(dest))
    # Figures on disk that no current document includes. They belong to the
    # superseded manuscripts being archived beside them, so they follow.
    #
    # A PNG whose PDF twin is included stays: the generators write both from one
    # call, so archiving the PNG would only mean it reappears on the next run and
    # the archive fills with stale copies of a live figure. What leaves is a stem
    # no current document mentions in any format.
    stems = {Path(f).stem for f in wanted}
    unused = sorted(p for p in (PAPER / "figures").iterdir()
                    if p.is_file() and p.name not in wanted and p.stem not in stems)
    if unused:
        dest = ARCHIVE / "figures_unused"
        if not args.dry_run:
            dest.mkdir(parents=True, exist_ok=True)
        for p in unused:
            size = p.stat().st_size
            moved += size
            n_mv += 1
            say(f"  figures/{p.name}  ({size/1024:.0f} KB, no longer included)")
            if not args.dry_run:
                shutil.move(str(p), str(dest / p.name))
    print(f"  ---- {n_mv} entries, {moved/1024/1024:.1f} MB")

    # ---- 4. the zip --------------------------------------------------------
    if not args.dry_run:
        zpath = PAPER / "gmd_submission.zip"
        with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
            for f in sorted(OUT.rglob("*")):
                if f.is_file():
                    z.write(f, f.relative_to(OUT))
        print(f"\nwrote {zpath.name}  ({zpath.stat().st_size/1024/1024:.2f} MB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
