"""
Numerical-consistency audit for thesis tables (T-P0-2)
======================================================
Builds the CANONICAL reference of R2/RMSE/MAE aggregates from the raw
per-horizon metric CSVs, so every value cited in thesis.tex tables can be
mapped to an exact source (mean-across-horizons vs H=12 vs best-horizon).

This resolves the "ConvLSTM appears at 5 different R2 values" and
"GNN-TAT at 3 values" findings: each is a different (model, feature,
aggregation, seed) combination. The audit prints them side by side.

Outputs:
  .docs/thesis/reviews/numerical_audit_report.md

Usage:
  python models/scripts/analysis/audit_metrics.py
"""
import sys
import io
from pathlib import Path

if sys.platform == "win32":
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")

import pandas as pd
import numpy as np

ROOT = Path(__file__).resolve().parents[3]
OUT_DIR = ROOT / ".docs" / "thesis" / "reviews"
OUT_MD = OUT_DIR / "numerical_audit_report.md"

# Canonical per-horizon metric CSVs (seed 42 unless noted).
# V2: the *_hmulti.csv holds the COMPLETE family (all ConvLSTM/ConvRNN/Transformer
# variants across all horizons); the single-model *_h12.csv files are partial.
SOURCES = {
    "V2_ConvLSTM_family": ROOT / "models/output/V2_Enhanced_Models/metrics_spatial_v2_refactored_hmulti.csv",
    "V4_GNN_TAT_family": ROOT / "models/output/V4_GNN_TAT_Models/metrics_spatial_v4_gnn_tat_h12.csv",
}

# R2 values flagged in the adversarial review (to be explained/mapped)
FLAGGED_CONVLSTM = [0.598, 0.628, 0.629, 0.642, 0.653]
FLAGGED_GNN_TAT = [0.516, 0.597, 0.628]


def aggregate(df):
    """Per (Model, Experiment): mean / H12 / best / worst R2, RMSE, MAE across horizons."""
    rows = []
    for (model, exp), g in df.groupby(["Model", "Experiment"]):
        g = g.sort_values("H")
        r2 = pd.to_numeric(g["R^2"], errors="coerce")
        rmse = pd.to_numeric(g["RMSE"], errors="coerce")
        mae = pd.to_numeric(g["MAE"], errors="coerce")
        h12 = g[g["H"] == 12]
        rows.append({
            "Model": model, "Experiment": exp, "n_H": len(g),
            "R2_mean": round(r2.mean(), 4),
            "R2_H12": round(pd.to_numeric(h12["R^2"], errors="coerce").mean(), 4) if len(h12) else np.nan,
            "R2_best": round(r2.max(), 4),
            "R2_worst": round(r2.min(), 4),
            "RMSE_mean": round(rmse.mean(), 2),
            "MAE_mean": round(mae.mean(), 2),
        })
    return pd.DataFrame(rows).sort_values(["Model", "Experiment"])


def closest(value, df, col):
    """Find the canonical aggregate closest to a flagged value."""
    best = None
    for _, r in df.iterrows():
        for agg in ("R2_mean", "R2_H12", "R2_best", "R2_worst"):
            v = r[agg]
            if pd.isna(v):
                continue
            d = abs(v - value)
            if best is None or d < best[0]:
                best = (d, r["Model"], r["Experiment"], agg, v)
    return best


def main():
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    lines = ["# Numerical Consistency Audit — Thesis Tables (T-P0-2)", ""]
    lines.append(f"Generated by `models/scripts/analysis/audit_metrics.py`.")
    lines.append("")
    lines.append("Maps each R2 value cited in thesis tables to its canonical "
                 "(model, feature, aggregation) source. Aggregation legend: "
                 "`R2_mean` = mean across H=1..12; `R2_H12` = value at H=12; "
                 "`R2_best`/`R2_worst` = max/min across horizons.")
    lines.append("")

    all_agg = {}
    for name, path in SOURCES.items():
        if not path.exists():
            lines.append(f"## {name}\n\n**MISSING**: `{path}`\n")
            print(f"  MISSING: {path}")
            continue
        df = pd.read_csv(path)
        agg = aggregate(df)
        all_agg[name] = agg
        lines.append(f"## {name}")
        lines.append(f"Source: `{path.relative_to(ROOT)}`")
        lines.append("")
        lines.append("| Model | Feature | R2_mean | R2_H12 | R2_best | R2_worst | RMSE_mean | MAE_mean |")
        lines.append("|-------|---------|---------|--------|---------|----------|-----------|----------|")
        for _, r in agg.iterrows():
            lines.append(f"| {r['Model']} | {r['Experiment']} | {r['R2_mean']} | "
                         f"{r['R2_H12']} | {r['R2_best']} | {r['R2_worst']} | "
                         f"{r['RMSE_mean']} | {r['MAE_mean']} |")
        lines.append("")
        print(f"  {name}: {len(agg)} (model,feature) combos from {path.name}")

    # Map flagged values
    lines.append("## Flagged-value mapping (adversarial review)")
    lines.append("")
    conv = all_agg.get("V2_ConvLSTM_family")
    gnn = all_agg.get("V4_GNN_TAT_family")

    if conv is not None:
        lines.append("### ConvLSTM family — the '5 different R2 values'")
        lines.append("")
        lines.append("| Flagged | Closest canonical | Model | Feature | Aggregation | Diff |")
        lines.append("|---------|-------------------|-------|---------|-------------|------|")
        for v in FLAGGED_CONVLSTM:
            c = closest(v, conv[conv["Model"].str.contains("ConvLSTM", case=False, na=False)], "R^2")
            if c:
                lines.append(f"| {v} | {c[4]} | {c[1]} | {c[2]} | {c[3]} | {c[0]:.4f} |")
        lines.append("")

    if gnn is not None:
        lines.append("### GNN-TAT family — the '3 different R2 values'")
        lines.append("")
        lines.append("| Flagged | Closest canonical | Model | Feature | Aggregation | Diff |")
        lines.append("|---------|-------------------|-------|---------|-------------|------|")
        for v in FLAGGED_GNN_TAT:
            c = closest(v, gnn, "R^2")
            if c:
                lines.append(f"| {v} | {c[4]} | {c[1]} | {c[2]} | {c[3]} | {c[0]:.4f} |")
        lines.append("")

    OUT_MD.write_text("\n".join(lines), encoding="utf-8")
    print(f"\n  Report written: {OUT_MD.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
